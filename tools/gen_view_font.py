#!/usr/bin/env python3
"""The large faces of the FM-1 view (fm1base/app.c, issue #107): Barlow Semi Condensed from fm1-base's assets, rendered at
sizes fm1-base's six roles do not have, into fm1base/d50_view_font.h.

  python3 tools/gen_view_font.py FM1_BASE_DIR fm1base/d50_view_font.h

A glyph is its lit box only: left (from the pen, signed), top (from the line's top), width, rows, then the rows' alphas
0..15, two to a byte, high nibble first (each row padded to a whole byte). app.c view_text draws it.
Barlow is under the SIL Open Font License 1.1 (fm1-base assets/fonts): these are bitmaps rendered from it.
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

# (name, file, px, first, last)
FACES = [("NAME", "BarlowSemiCondensed-Bold.ttf", 43, 32, 126),     # the patch name: nearly three times B's 15 px (45 leaves Afterthought too wide)
         ("STAT", "BarlowSemiCondensed-SemiBold.ttf", 36, 32, 95)]  # the status lines: three times XS's 12 px (capitals)


def render(path, px, first, last):
    font = ImageFont.truetype(str(path), px)
    asc, desc = font.getmetrics()
    h = asc + desc
    glyphs = []
    for ch in range(first, last + 1):
        c = chr(ch)
        adv = int(round(font.getlength(c)))
        pad = px
        img = Image.new("L", (adv + 2 * pad, h), 0)
        ImageDraw.Draw(img).text((pad, 0), c, font=font, fill=255)
        box = img.getbbox()
        if not box:
            glyphs.append((adv, 0, 0, 0, 0, b""))
            continue
        x0, y0, x1, y1 = box
        w, n = x1 - x0, y1 - y0
        rows = bytearray()
        for y in range(y0, y1):
            row = [min(15, (img.getpixel((x, y)) + 8) // 17) for x in range(x0, x1)] + [0]
            for x in range(0, w, 2):
                rows.append(row[x] << 4 | row[x + 1])
        glyphs.append((adv, x0 - pad, y0, w, n, bytes(rows)))
    return h, glyphs


def main(base, out):
    fonts = Path(base) / "assets" / "fonts"
    lines = ["/* generated by tools/gen_view_font.py: the FM-1 view's large faces (issue #107), Barlow Semi Condensed",
             " * (SIL Open Font License 1.1, from fm1-base's assets). A glyph: left (signed, from the pen), top, width, rows, then",
             " * the rows' alphas 0..15, two a byte, high nibble first, each row padded to a byte. */",
             "#pragma once", "#include <stdint.h>", "",
             "typedef struct {", "    uint8_t h, first, last;", "    const uint8_t *adv;", "    const uint16_t *off;",
             "    const uint8_t *data;", "} view_face_t;", ""]
    total = 0
    for name, file, px, first, last in FACES:
        h, glyphs = render(fonts / file, px, first, last)
        data, offs = bytearray(), []
        for adv, left, top, w, n, rows in glyphs:
            offs.append(len(data))
            data += bytes([left & 0xFF, top, w, n]) + rows
        assert len(data) < 65536, name
        total += len(data)
        lines.append(f"static const uint8_t VIEW_{name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const uint16_t VIEW_{name}_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};")
        lines.append(f"static const uint8_t VIEW_{name}_ADV[{len(glyphs)}] = {{" + ", ".join(str(g[0]) for g in glyphs) + "};")
        lines.append(f"static const view_face_t VIEW_{name} = {{ {h}, {first}, {last}, VIEW_{name}_ADV, VIEW_{name}_OFF, "
                     f"VIEW_{name}_DATA }};")
        lines.append("")
        print(f"view font {name}: {file} {px}px, line {h}, {len(data)} B")
    print(f"view fonts: {total} B")
    Path(out).write_text("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
